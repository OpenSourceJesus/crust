# DLL name -> (function names, data names), in search order. msvcrt comes
# first: the two names both export (__C_specific_handler, _local_unwind) are
# the C runtime's.
_TABLES = [("msvcrt.dll", MSVCRT_FUNCS, MSVCRT_DATA),
           ("KERNEL32.dll", KERNEL32_FUNCS, "")]

_index = None


def _build():
    idx = {}
    for dll, funcs, data in _TABLES:
        for n in funcs.split():
            if n not in idx:
                idx[n] = (dll, False)
        for n in data.split():
            if n not in idx:
                idx[n] = (dll, True)
    return idx


def lookup(name):
    """(dll, is_data) for an exported symbol, or None if no known DLL has
    it."""
    global _index
    if _index is None:
        _index = _build()
    return _index.get(name, None)


def default_dlls():
    """The DLLs searched when a program does not name any."""
    return [t[0] for t in _TABLES]
