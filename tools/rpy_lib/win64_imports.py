"""Export tables for the Windows DLLs rlink links against by name.

rlink writes a PE executable's import table itself (see rlink_pe.py), so it
needs to know, without any file from a Windows system being present, which
DLL provides each symbol a program leaves undefined, and whether that symbol
is a function (reached through a jump stub rlink generates) or data (which
must be reached through its import-address-table slot, `__imp_NAME`, since
a stub is code and cannot stand in for a variable).

Provenance -- facts about the DLLs' interfaces, not code from them:

* Names: the `__imp_` symbols of MinGW-w64's import libraries,
  libmsvcrt-os.a (exactly what msvcrt.dll exports, without the MinGW
  emulations libmsvcrt.a layers on top) and libkernel32.a, from the
  x86_64-w64-mingw32 packages of mingw-w64 11.0.
* Data versus code: an import library marks a data export by giving it no
  code thunk -- but MinGW also withholds the thunk from functions it
  substitutes with its own implementations (sin, pow, atexit, ...). So each
  candidate was checked against Wine 9.0's msvcrt.dll, whose export table
  says whether an address lands in an executable section. DATA below is the
  set both agree on, plus five Wine does not export at all (_fileinfo,
  _mbcasemap, daylight, timezone, tzname), which Microsoft documents as
  variables.

Regenerating needs those two packages; see WINDOWS.md.
"""

